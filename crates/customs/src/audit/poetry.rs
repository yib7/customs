//! `poetry.lock`: one `[[package]]` table per locked package.

use std::path::Path;

use customs_scan::Ecosystem;
use serde::Deserialize;
use toml::Spanned;

use super::{host_of, known_registry, LineIndex, Parsed, SkipKind};

#[derive(Deserialize)]
struct Lock {
    #[serde(default)]
    package: Vec<Package>,
}

#[derive(Deserialize)]
struct Package {
    name: Spanned<String>,
    version: String,
    #[serde(default)]
    source: Option<Source>,
}

#[derive(Deserialize)]
struct Source {
    #[serde(rename = "type", default)]
    kind: String,
    #[serde(default)]
    url: String,
}

pub(super) fn parse(text: &str, file: &Path, out: &mut Parsed) -> Result<(), String> {
    let lock: Lock = toml::from_str(text).map_err(|e| e.to_string().trim_end().to_string())?;
    let lines = LineIndex::new(text);
    for p in lock.package {
        let line = lines.line(p.name.span().start);
        let name = p.name.get_ref();
        let spec = format!("{name}=={}", p.version);
        match p.source {
            None => out.dep(Ecosystem::Pypi, name, &p.version, file, line),
            Some(s) => match s.kind.as_str() {
                // Path dependencies are the project's own code.
                "directory" => {}
                "legacy" if known_registry(&s.url) => {
                    out.dep(Ecosystem::Pypi, name, &p.version, file, line)
                }
                "legacy" => out.skip(
                    file,
                    line,
                    &spec,
                    SkipKind::CustomIndex,
                    format!("from a custom package index ({})", host_of(&s.url)),
                ),
                "file" => out.skip(
                    file,
                    line,
                    &spec,
                    SkipKind::Local,
                    "installed from a local file",
                ),
                other => out.skip(
                    file,
                    line,
                    &spec,
                    SkipKind::Source,
                    format!("installed from a {other} source ({})", s.url),
                ),
            },
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::super::tests::pins;
    use super::*;

    const LOCK: &str = r#"# This file is automatically @generated by Poetry 1.8.2 and should not be changed by hand.

[[package]]
name = "certifi"
version = "2024.2.2"
description = "Python package for providing Mozilla's CA Bundle."
optional = false
python-versions = ">=3.6"
files = [
    {file = "certifi-2024.2.2-py3-none-any.whl", hash = "sha256:dc383c07b76109f368f6106eee2b593b04a011ea4d55f652c6ca24a754d1cdd1"},
]

[[package]]
name = "Flask"
version = "3.0.2"
description = "A simple framework for building complex web applications."
optional = false
python-versions = ">=3.8"
files = []

[package.dependencies]
click = ">=8.1.3"

[package.extras]
async = ["asgiref (>=3.2)"]

[[package]]
name = "internal-lib"
version = "0.4.0"
description = ""
optional = false
python-versions = "*"
files = []

[package.source]
type = "legacy"
url = "https://pypi.corp.example/simple"
reference = "corp"

[[package]]
name = "mylib"
version = "0.1.0"
description = ""
optional = false
python-versions = "*"
files = []
develop = true

[package.source]
type = "directory"
url = "../mylib"

[[package]]
name = "forked"
version = "1.0.0"
description = ""
optional = false
python-versions = "*"
files = []

[package.source]
type = "git"
url = "https://github.com/x/forked.git"
reference = "main"
resolved_reference = "abc123"

[metadata]
lock-version = "2.0"
python-versions = "^3.11"
content-hash = "deadbeef"
"#;

    #[test]
    fn poetry_lock() {
        let mut p = Parsed::default();
        parse(LOCK, Path::new("poetry.lock"), &mut p).unwrap();
        assert_eq!(
            pins(&p),
            vec![
                ("certifi".into(), "2024.2.2".into(), 4),
                ("flask".into(), "3.0.2".into(), 14),
            ]
        );
        assert_eq!(p.skipped.len(), 2);
        assert_eq!(p.skipped[0].line, 28);
        assert!(p.skipped[0].reason.contains("pypi.corp.example"));
        assert_eq!(p.skipped[1].spec, "forked==1.0.0");
        assert!(p.skipped[1].reason.contains("git"));
        assert!(parse("[[package]]\nname = 1\n", Path::new("x"), &mut p).is_err());
    }
}
