//! `yarn.lock`, classic (v1) and berry (v2+). Each entry is an unindented header listing
//! the specs it satisfies, followed by indented fields; only `version`, `resolved`
//! (classic), and `resolution` (berry) are needed.

use std::path::Path;

use super::{npm_pin, split_npm_spec, Parsed};

/// Protocols of a project's own packages, skipped silently.
const LOCAL_PROTOCOLS: &[&str] = &["workspace:", "link:", "portal:"];

#[derive(Default)]
struct Entry {
    line: usize,
    specs: Vec<String>,
    version: Option<String>,
    resolved: Option<String>,
    resolution: Option<String>,
}

pub(super) fn parse(text: &str, file: &Path, out: &mut Parsed) -> Result<(), String> {
    let mut cur: Option<Entry> = None;
    for (i, raw) in text.lines().enumerate() {
        let trimmed = raw.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let indent = raw.len() - raw.trim_start().len();
        if indent == 0 {
            if let Some(e) = cur.take() {
                finish(e, file, out);
            }
            let Some(header) = trimmed.strip_suffix(':') else {
                continue;
            };
            cur = Some(Entry {
                line: i + 1,
                specs: header
                    .split(',')
                    .map(|s| s.trim().trim_matches('"').to_string())
                    .filter(|s| !s.is_empty())
                    .collect(),
                ..Entry::default()
            });
            continue;
        }
        let Some(e) = cur.as_mut() else {
            continue;
        };
        // Fields of the entry itself, not of its nested `dependencies` maps.
        if indent != 2 {
            continue;
        }
        let Some((key, value)) = trimmed.split_once(|c: char| c.is_whitespace()) else {
            continue;
        };
        let value = Some(value.trim().trim_matches('"').to_string());
        match key.trim_end_matches(':') {
            "version" => e.version = value,
            "resolved" => e.resolved = value,
            "resolution" => e.resolution = value,
            _ => {}
        }
    }
    if let Some(e) = cur.take() {
        finish(e, file, out);
    }
    Ok(())
}

fn finish(e: Entry, file: &Path, out: &mut Parsed) {
    let Some(first) = e.specs.first() else {
        return;
    };
    if first == "__metadata" {
        return;
    }
    let ranges: Vec<&str> = e
        .specs
        .iter()
        .filter_map(|s| split_npm_spec(s).map(|(_, r)| r))
        .collect();
    if ranges
        .iter()
        .any(|r| LOCAL_PROTOCOLS.iter().any(|p| r.starts_with(p)))
    {
        return;
    }
    // Berry lists patched packages next to the unpatched entry, which is checked.
    if ranges.iter().any(|r| r.starts_with("patch:")) {
        return;
    }
    let Some(version) = e.version.as_deref() else {
        out.skip(file, e.line, first, "no version recorded");
        return;
    };
    // Berry: `resolution: "real-name@npm:1.2.3"` names the package actually installed.
    if let Some(res) = &e.resolution {
        match split_npm_spec(res) {
            Some((name, r)) if r.starts_with("npm:") => {
                npm_pin(out, file, e.line, name, version, None)
            }
            _ => out.skip(
                file,
                e.line,
                res,
                "not a registry package (git, URL, or local path)",
            ),
        }
        return;
    }
    // Classic: the header names the package; `alias@npm:real@range` installs `real`.
    let Some((name, range)) = split_npm_spec(first) else {
        out.skip(file, e.line, first, "could not parse the entry");
        return;
    };
    let name = range
        .strip_prefix("npm:")
        .and_then(split_npm_spec)
        .map(|(real, _)| real)
        .unwrap_or(name);
    if range.contains("://") || range.starts_with("git") || range.starts_with("file:") {
        out.skip(
            file,
            e.line,
            first,
            "not a registry package (git, URL, or local path)",
        );
        return;
    }
    npm_pin(out, file, e.line, name, version, e.resolved.as_deref());
}

